import { request } from 'node:http';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, cpSync, rmSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { createProject, assetPath, preparePublic, fingerprint, recordOutput, recordGate } from '../scripts/projects.mjs';
import { createDashboard, listProjects } from '../scripts/dashboard.mjs';
const original = process.cwd();
function fixture(t) {
    const dir = mkdtempSync(join(tmpdir(), 'techno-projects-'));
    process.chdir(dir);
    t.after(() => { process.chdir(original); rmSync(dir, { recursive: true, force: true }); });
    return (path, text) => { mkdirSync(resolve(path, '..'), { recursive: true }); writeFileSync(path, text); };
}
test('project creation rejects traversal and never overwrites originals', t => {
    const put = fixture(t);
    assert.throws(() => createProject('../outside'));
    const p = createProject('my-reel', 'My Reel');
    put(join(p.raw, 'original.mov'), 'original');
    assert.throws(() => createProject('my-reel'));
    assert.equal(readFileSync(join(p.raw, 'original.mov'), 'utf8'), 'original');
    assert.equal(JSON.parse(readFileSync(join(p.root, 'project.json'))).name, 'My Reel');
    assert.throws(() => assetPath('reels/my-reel/../../secret'));
});
test('render staging selects only project working assets and shared media', t => {
    const put = fixture(t);
    const p = createProject('one');
    createProject('two');
    put(join(p.working, 'script.json'), '{}');
    put(join(p.scenes, 'Custom.tsx'), 'scene');
    put(join(p.raw, 'secret.mov'), 'raw');
    put('projects/two/working/private.txt', 'other');
    put('public/sfx/pop.wav', 'sound');
    const staged = preparePublic('one');
    assert.equal(readFileSync(join(staged, 'reels/one/script.json'), 'utf8'), '{}');
    assert.ok(!existsSync(join(staged, 'reels/two')));
    assert.ok(!existsSync(join(staged, 'reels/one/scenes')));
    assert.ok(!existsSync(join(staged, 'raw')));
    assert.ok(existsSync(join(staged, 'sfx/pop.wav')));
});
test('output freshness changes after script edits and handles broken metadata', t => {
    const put = fixture(t);
    const p = createProject('one');
    put(join(p.working, 'script.json'), '{"shots":[]}');
    recordOutput('one', 'export');
    assert.equal(listProjects()[0].freshness.export, 'current');
    put(join(p.working, 'script.json'), '{"shots":[{"say":"changed"}]}');
    assert.equal(listProjects()[0].freshness.export, 'outdated');
    recordGate('one', 'pace', []);
    assert.equal(listProjects()[0].checks.pace.current, false);
    put(join(p.root, 'project.json'), 'bad json');
    assert.equal(listProjects()[0].errors.length, 1);
});
test('migration preserves sources, retries safely, and refuses conflicts before copying', t => {
    const put = fixture(t);
    cpSync(join(original, 'scripts'), 'scripts', { recursive: true });
    put('public/reels/one/script.json', '{"shots":[]}');
    put('out/one/one.mp4', 'video');
    put('out/one/one-draft.mp4', 'draft');
    const run = (...args) => spawnSync(process.execPath, ['scripts/migrate.mjs', ...args], { encoding: 'utf8' });
    assert.equal(run().status, 0);
    assert.ok(!existsSync('projects/one'));
    assert.equal(run('--apply').status, 0);
    assert.ok(existsSync('public/reels/one/script.json'));
    assert.equal(readFileSync('projects/one/export/one.mp4', 'utf8'), 'video');
    assert.ok(existsSync('projects/one/preview/draft.mp4'));
    assert.equal(run('--apply').status, 0);
    put('projects/one/working/script.json', 'changed');
    put('public/reels/one/new.txt', 'new');
    assert.equal(run('--apply').status, 1);
    assert.ok(!existsSync('projects/one/working/new.txt'));
    assert.equal(run('--rollback').status, 1);
    assert.ok(existsSync('projects/one/export/one.mp4'));
    put('projects/one/working/script.json', '{"shots":[]}');
    assert.equal(run('--rollback').status, 0);
    assert.ok(!existsSync('projects/one/export/one.mp4'));
    assert.ok(existsSync('out/one/one.mp4'));
});
test('dashboard serves video ranges, blocks writes, hostile hosts and symlink escapes', async (t) => {
    const put = fixture(t);
    const p = createProject('one');
    put(join(p.exports, 'one.mp4'), '0123456789');
    put('private.txt', 'secret');
    symlinkSync(resolve('private.txt'), join(p.raw, 'escape.txt'));
    const server = createDashboard();
    await new Promise(r => server.listen(0, '127.0.0.1', r));
    t.after(() => new Promise(r => server.close(r)));
    const root = `http://127.0.0.1:${server.address().port}`;
    const range = await fetch(root + '/files/one/export/one.mp4', { headers: { range: 'bytes=2-5' } });
    assert.equal(range.status, 206);
    assert.equal(await range.text(), '2345');
    assert.equal((await fetch(root + '/api/projects', { method: 'POST' })).status, 405);
    assert.equal((await fetch(root + '/files/one/raw/escape.txt')).status, 404);
    mkdirSync('outside');
    put('outside/secret.txt', 'secret');
    rmSync(p.raw, { recursive: true });
    symlinkSync(resolve('outside'), p.raw);
    assert.equal((await fetch(root + '/files/one/raw/secret.txt')).status, 404);
    assert.equal(listProjects()[0].files.raw.length, 0);
    const hostile = await new Promise((done, reject) => { const req = request(root + '/api/projects', { headers: { host: 'evil.example' } }, res => { res.resume(); done(res.statusCode); }); req.on('error', reject); req.end(); });
    assert.equal(hostile, 403);
    assert.equal((await fetch(root + '/files/one/export/one.mp4', { headers: { range: 'bytes=99-' } })).status, 416);
    assert.equal((await fetch(root + '/files/one/export/%2e%2e%2f%2e%2e%2fprivate.txt')).status, 404);
});
